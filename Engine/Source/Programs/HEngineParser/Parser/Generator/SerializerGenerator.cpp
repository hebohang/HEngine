namespace
{
    void appendInclude(Mustache::data& includes, const std::string& path)
    {
        includes.push_back(Mustache::data("headfile_name", path));
    }

    std::string makeShim(const std::string& target)
    {
        return "// Generated by HEngineParser. Compatibility include; do not edit.\n#pragma once\n#include \"" + target +
               "\"\n";
    }
}

namespace Generator
{
    SerializerGenerator::SerializerGenerator(fs::path outputRoot, std::string moduleName) :
        GeneratorInterface(std::move(outputRoot), std::move(moduleName))
    {}

    bool SerializerGenerator::initialize(std::string& error)
    {
        auto* templates = TemplateManager::getInstance();
        return templates->loadTemplates("allSerializer.h", error) &&
               templates->loadTemplates("commonSerializerGenHeaderFile", error) &&
               templates->loadTemplates("commonSerializerGenSourceFile", error);
    }

    bool SerializerGenerator::generate(const SchemaMoudle& schema, std::string& error)
    {
        const std::string headerPath = makeSerializerHeaderPath(schema);
        const std::string sourcePath = makeSerializerSourcePath(schema);

        Mustache::data headerData;
        Mustache::data dependencyIncludes(Mustache::data::type::list);
        Mustache::data classDefinitions(Mustache::data::type::list);
        std::set<std::string> dependencyPaths;

        for (const auto& classInfo : schema.classes)
        {
            if (!classInfo->shouldCompileFilds())
            {
                continue;
            }

            Mustache::data classDefinition;
            genClassRenderData(classInfo, classDefinition);
            classDefinitions.push_back(classDefinition);

            for (const auto& base : classInfo->m_base_classes)
            {
                if (!base->dependencyOutputIdentity.empty() &&
                    base->dependencyOutputIdentity != classInfo->m_output_identity)
                {
                    fs::path dependency(base->dependencyOutputIdentity);
                    dependency.replace_extension("gen.h");
                    dependencyPaths.emplace("_generated/serializer/" + dependency.generic_string());
                }
            }

            for (const auto& field : classInfo->m_fields)
            {
                if (!field->shouldCompile())
                {
                    continue;
                }
                for (const auto* dependencyIdentity :
                     {&field->m_dependency_output_identity, &field->m_container_dependency_output_identity})
                {
                    if (!dependencyIdentity->empty() && *dependencyIdentity != classInfo->m_output_identity)
                    {
                        fs::path dependency(*dependencyIdentity);
                        dependency.replace_extension("gen.h");
                        dependencyPaths.emplace("_generated/serializer/" + dependency.generic_string());
                    }
                }
            }
        }

        for (const auto& dependencyPath : dependencyPaths)
        {
            appendInclude(dependencyIncludes, dependencyPath);
        }
        headerData.set("include_headfiles", dependencyIncludes);
        headerData.set("class_defines", classDefinitions);

        std::string headerContent;
        if (!TemplateManager::getInstance()->renderByTemplate(
                "commonSerializerGenHeaderFile", headerData, headerContent, error) ||
            !writeOutput(headerPath, headerContent, error))
        {
            return false;
        }

        Mustache::data sourceData;
        Mustache::data sourceIncludes(Mustache::data::type::list);
        appendInclude(sourceIncludes, schema.sourceInclude);
        appendInclude(sourceIncludes, headerPath);
        sourceData.set("include_headfiles", sourceIncludes);
        sourceData.set("class_defines", classDefinitions);

        std::string sourceContent;
        if (!TemplateManager::getInstance()->renderByTemplate(
                "commonSerializerGenSourceFile", sourceData, sourceContent, error) ||
            !writeOutput(sourcePath, sourceContent, error))
        {
            return false;
        }

        m_schemas.emplace_back(schema);
        m_header_files.emplace_back(headerPath);
        m_source_files.emplace_back(sourcePath);
        return true;
    }

    bool SerializerGenerator::finish(std::string& error)
    {
        Mustache::data aggregateData;
        Mustache::data aggregateIncludes(Mustache::data::type::list);
        for (const auto& sourceFile : m_source_files)
        {
            appendInclude(aggregateIncludes, sourceFile);
        }
        aggregateData.set("include_headfiles", aggregateIncludes);

        std::string aggregateContent;
        if (!TemplateManager::getInstance()->renderByTemplate(
                "allSerializer.h", aggregateData, aggregateContent, error) ||
            !writeOutput("_generated/serializer/all_serializer.hpp", aggregateContent, error))
        {
            return false;
        }

        aggregateIncludes = Mustache::data(Mustache::data::type::list);
        for (const auto& headerFile : m_header_files)
        {
            appendInclude(aggregateIncludes, headerFile);
        }
        aggregateData.set("include_headfiles", aggregateIncludes);
        if (!TemplateManager::getInstance()->renderByTemplate(
                "allSerializer.h", aggregateData, aggregateContent, error) ||
            !writeOutput("_generated/serializer/all_serializer.h", aggregateContent, error))
        {
            return false;
        }

        std::map<std::string, size_t> basenameCounts;
        for (const auto& schema : m_schemas)
        {
            ++basenameCounts[fs::path(schema.logicalSource).filename().generic_string()];
        }

        for (const auto& schema : m_schemas)
        {
            const std::string basename = fs::path(schema.logicalSource).filename().generic_string();
            if (basenameCounts[basename] != 1)
            {
                continue;
            }

            const std::string canonicalHeader = makeSerializerHeaderPath(schema);
            const std::string compatibilityHeader = makeCompatibilitySerializerHeaderPath(schema);
            if (canonicalHeader != compatibilityHeader &&
                !writeOutput(compatibilityHeader, makeShim(canonicalHeader), error))
            {
                return false;
            }

            const std::string canonicalSource = makeSerializerSourcePath(schema);
            const std::string compatibilitySource = makeCompatibilitySerializerSourcePath(schema);
            if (canonicalSource != compatibilitySource &&
                !writeOutput(compatibilitySource, makeShim(canonicalSource), error))
            {
                return false;
            }
        }

        std::sort(m_outputs.begin(), m_outputs.end());
        return true;
    }
} // namespace Generator
